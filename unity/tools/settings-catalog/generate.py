import json, sys
BS = chr(92)
d = json.load(open(sys.argv[1], encoding='utf-8'))
fix = {
    'graphics.preset': [["auto", "Automático"], ["verylow", "Muito baixa"], ["low", "Baixa"], ["medium", "Média"], ["high", "Alta"], ["ultra", "Ultra"], ["custom", "Personalizada"]],
    'interface.scale': [["auto", "Automático"], ["0.75", "75%"], ["0.85", "85%"], ["0.9", "90%"], ["1", "100%"], ["1.1", "110%"], ["1.25", "125%"], ["1.5", "150%"]],
    'inventory.default_sort': [["0", "Ordem padrão"], ["1", "Nome (A–Z)"], ["2", "Nome (Z–A)"], ["3", "Mais novos"], ["4", "Mais antigos"], ["5", "Maiores"], ["6", "Menores"], ["7", "Tipo"], ["8", "Usados há pouco"]],
}
def cs(s):
    if s is None: return 'null'
    return '"' + str(s).replace(BS, BS + BS).replace('"', BS + '"').replace('\n', BS + 'n') + '"'
def num(v):
    if isinstance(v, bool): return '1' if v else '0'
    return repr(float(v)) if isinstance(v, float) else str(v)
def default(v):
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, float): return repr(v)
    return str(v)
lines = []
problems = []
for x in d:
    for k in ('default', 'min', 'max', 'step', 'label', 'help', 'unavailable'):
        if isinstance(x.get(k), dict): problems.append((x['id'], k, x[k]))
    ch = fix.get(x['id'], x.get('choices'))
    if isinstance(ch, dict): problems.append((x['id'], 'choices', ch)); ch = None
    if x['kind'] == 'Choice' and not ch and not x.get('choiceSource'): ch = [[str(x['default']), '—']]
    props = []
    for k in ('min', 'max', 'step'):
        if k in x: props.append(k.capitalize() + ' = ' + num(x[k]))
    for k, name in (('unit', 'Unit'), ('group', 'Group'), ('unavailable', 'Unavailable'), ('button', 'ButtonText'), ('buttonText', 'ButtonText'), ('confirm', 'Confirm')):
        if x.get(k) not in (None, ''): props.append(name + ' = ' + cs(x[k] if not isinstance(x[k], dict) else x[k]['expr']))
    if x.get('choiceSource'): props.append('Device = true')
    if 'column' in x and not isinstance(x['column'], dict): props.append('Column = ' + str(x['column']))
    for k, name in (('restartRequired', 'RestartRequired'), ('presetControlled', 'PresetControlled')):
        if x.get(k) is True: props.append(name + ' = true')
    if ch: props.append('Choices = new[] { ' + ', '.join('(' + cs(a) + ', ' + cs(b) + ')' for a, b in ch) + ' }')
    if x.get('keywords'): props.append('Keywords = new[] { ' + ', '.join(cs(k) for k in x['keywords'] if not isinstance(k, dict)) + ' }')
    lines.append('            new SettingDef(' + ', '.join([cs(x['id']), cs(x['category']), cs(x['tab']), cs(x['label']), cs(x['help']), cs(x['kind']), cs(default(x['default']))]) + ')' + (' { ' + ', '.join(props) + ' }' if props else '') + ',')
out = '''// <auto-generated>
// Gerado a partir do catálogo de configurações do cliente Godot (client/Scripts/Settings/SettingsCatalog*.cs) por tools: os mesmos ids, rótulos, textos, padrões,
// limites e escolhas. O que cada configuração faz no Unity fica em SettingsEffects.cs; o que o Unity ainda não faz aparece desligado com o motivo.
// </auto-generated>
namespace LifeVerse.Unity.UI
{
    public static partial class SettingsCatalog
    {
        private static readonly SettingDef[] Raw =
        {
''' + '\n'.join(lines) + '''
        };
    }
}
'''
open(sys.argv[2], 'w', encoding='utf-8').write(out)
print(len(lines), 'problems:', problems)
