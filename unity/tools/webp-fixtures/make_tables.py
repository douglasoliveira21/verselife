"""Writes Vp8Tables.cs: the constant tables of the VP8 format (RFC 6386), read from the libwebp that the portable Godot of the repository carries (BSD 3-clause, (c) Google).

    python unity/tools/webp-fixtures/make_tables.py

The tables are found by the first values the specification gives for each one; run it again only if the decoder needs another table.
"""
import base64
import os
import struct

REPO = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
GODOT = os.path.join(REPO, ".tools", "godot-4.7.2", "Godot_v4.7.2-stable_mono_win64", "Godot_v4.7.2-stable_mono_win64.exe")
OUT = os.path.join(REPO, "unity", "UnityClient", "Assets", "LifeVerse", "World", "Webp", "Vp8Tables.cs")


def main():
    data = open(GODOT, "rb").read()

    def block(prefix, size):
        at = data.find(prefix)
        if at < 0:
            raise SystemExit("table not found")
        return data[at:at + size]

    coefficients = block(bytes([128] * 33 + [253, 136, 254, 255, 228, 219, 128, 128, 128, 128, 128, 189, 129, 242]), 4 * 8 * 3 * 11)
    updates = block(bytes([255] * 33 + [176, 246, 255, 255, 255, 255, 255, 255, 255, 255, 255, 223, 241, 252]), 4 * 8 * 3 * 11)
    modes = block(bytes([231, 120, 48, 89, 115, 113, 120, 152, 112, 152, 179, 64]), 10 * 10 * 9)
    dc = block(bytes([4, 5, 6, 7, 8, 9, 10, 10, 11, 12, 13, 14, 15, 16, 17, 17]), 128)
    start = data.find(struct.pack("<16H", *range(4, 20)))
    while start >= 0:
        ac = struct.unpack("<128H", data[start:start + 256])
        if ac[-1] == 284 and all(b >= a for a, b in zip(ac, ac[1:])):
            break
        start = data.find(struct.pack("<16H", *range(4, 20)), start + 2)
    distances = block(bytes([0x18, 0x07, 0x17, 0x19, 0x28, 0x06, 0x27, 0x29, 0x16, 0x1A, 0x26, 0x2A]), 120)
    assert sum(dc) == 8168 and dc[-1] == 157 and len(set(distances)) == 120

    def packed(name, comment, value):
        text = base64.b64encode(value).decode()
        lines = [text[i:i + 160] for i in range(0, len(text), 160)]
        body = " +\n".join('            "%s"' % line for line in lines)
        return "        /// <summary>%s</summary>\n        internal static readonly byte[] %s = Convert.FromBase64String(\n%s);\n" % (comment, name, body)

    source = """// Generated by unity/tools/webp-fixtures/make_tables.py. The constant tables of the VP8 and WebP lossless formats (RFC 6386 and the WebP specification),
// as in libwebp, Copyright (c) 2010 Google Inc., BSD 3-clause licence.
using System;

namespace LifeVerse.Unity.World.Webp
{
    internal static class Vp8Tables
    {
""" + packed("Coefficients", "Starting probabilities of the coefficient tokens: [type 4][band 8][context 3][11].", coefficients) + packed(
        "CoefficientUpdates", "The probability that each of those is replaced in the frame header.", updates) + packed(
        "BlockModes", "Probabilities of a 4x4 prediction mode: [mode above 10][mode on the left 10][9].", modes) + packed(
        "DcSteps", "Dequantization step of the first coefficient, by quantizer index.", dc) + packed(
        "DistanceMap", "Lossless: the 120 short distances as a neighbourhood: row in the high half, 8 - column in the low half.", distances) + (
        "        /// <summary>Dequantization step of the other coefficients, by quantizer index.</summary>\n        internal static readonly ushort[] AcSteps = { %s };\n    }\n}\n" % ", ".join(map(str, ac)))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8", newline="\n").write(source)
    print("ok", OUT)


if __name__ == "__main__":
    main()
